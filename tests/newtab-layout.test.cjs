const assert = require('node:assert/strict');
const { setup, fire, queryAll, settle } = require('./newtab-dom.cjs');
const handle = node => queryAll(node, '.layout-handle')[0];
const rect = (left, top, width = 200, height = 60) => ({ left, top, width, height });
const snapshot = value => JSON.parse(JSON.stringify(value));

(async () => {
  const page = setup();
  await settle();
  const original = JSON.stringify(page.store.newtabGroups);
  assert.equal(page.store.newtabLayout, undefined, 'Opening the page does not rewrite the existing layout');
  fire(page.element('edit-toggle'), 'click');
  page.element('search-row').rect = rect(300, 80, 600);
  page.element('mail-links').rect = rect(1100, 20);
  page.cards()[0].rect = rect(300, 200);
  page.cards()[1].rect = rect(520, 200);
  const key = `group:${page.store.newtabGroups[0].id}`;
  const otherKey = `group:${page.store.newtabGroups[1].id}`;
  function drag(node, dx, dy, type = 'pointerup') {
    fire(handle(node), 'pointerdown', { button: 0, clientX: 10, clientY: 10 });
    fire(page.body, 'pointermove', { clientX: 10 + dx, clientY: 10 + dy });
    fire(page.body, type, { type });
  }
  const initialWrites = page.writes.length;
  drag(page.cards()[0], 0, 0);
  await settle();
  assert.equal(page.writes.length, initialWrites, 'Clicking a handle does not change the layout');
  drag(page.cards()[0], 220, 0);
  await settle();
  assert.equal(page.store.newtabLayout, undefined, 'An overlapping first move leaves the original flow intact');
  assert.equal(page.body.classList.contains('canvas-layout'), false);
  drag(page.cards()[0], 120, 300);
  await settle();
  assert.deepEqual(snapshot(page.store.newtabLayout[key]), { x: 420, y: 500, width: 200 });
  assert.deepEqual(snapshot(page.store.newtabLayout[otherKey]), { x: 520, y: 200, width: 200 }, 'The other group stays put');
  assert.deepEqual(snapshot(page.store.newtabLayout.search), { x: 300, y: 80, width: 600 });
  assert.equal(JSON.stringify(page.store.newtabGroups), original, 'Moving sections preserves shortcut order');
  const accepted = snapshot(page.store.newtabLayout);
  const writes = page.writes.length;
  drag(page.cards()[0], 100, -300); // Exactly on top of the other group.
  await settle();
  assert.equal(page.cards()[0].style.left, '420px');
  assert.equal(page.cards()[0].style.top, '500px');
  assert.deepEqual(snapshot(page.store.newtabLayout), accepted, 'Rejected drops preserve the entire saved arrangement');
  assert.equal(page.writes.length, writes, 'Rejected drops do not write storage');
  drag(page.cards()[0], 100, 100, 'pointercancel');
  assert.equal(page.cards()[0].style.top, '500px', 'Pointer cancellation returns to start');
  fire(handle(page.cards()[0]), 'pointerdown', { clientX: 10, clientY: 10 });
  fire(page.body, 'pointermove', { clientX: 30, clientY: 40 });
  fire(page.body, 'keydown', { key: 'Escape' });
  assert.equal(page.cards()[0].style.left, '420px', 'Escape cancels the move');
  // Keyboard moves use the same collision rule as pointer moves.
  page.cards()[1].rect.height = 300;
  fire(handle(page.cards()[0]), 'keydown', { key: 'ArrowUp', shiftKey: true });
  await settle();
  assert.equal(page.store.newtabLayout[key].y, 500, 'Keyboard overlap returns to start');
  page.cards()[1].rect.height = 60;
  fire(handle(page.cards()[0]), 'keydown', { key: 'ArrowRight', shiftKey: true });
  await settle();
  assert.equal(page.store.newtabLayout[key].x, 440, 'Keyboard movement also uses canvas coordinates');
  drag(page.cards()[0], 1900, 1500);
  await settle();
  assert.equal(page.store.newtabLayout[key].x, 2340, 'The canvas extends beyond the viewport');
  assert.ok(parseFloat(page.body.style.minWidth) >= 2540);
  assert.ok(parseFloat(page.body.style.minHeight) >= 2000);
  fire(page.element('edit-toggle'), 'click');
  assert.equal(page.cards()[0].style.left, '2340px', 'Done editing keeps positions');
  const reopened = setup({ stored: page.store });
  await settle();
  assert.equal(reopened.cards()[0].style.left, '2340px', 'Reopening preserves document coordinates');
  assert.equal(reopened.cards()[0].style.width, '200px', 'Reopening preserves section widths');
  assert.equal(reopened.element('search-row').style.left, '300px');
  fire(reopened.element('edit-toggle'), 'click');
  reopened.element('new-group-name').value = 'Added';
  fire(reopened.element('new-group'), 'submit');
  await settle();
  const added = reopened.store.newtabGroups.at(-1);
  const addedKey = `group:${added.id}`;
  assert.ok(reopened.store.newtabLayout[addedKey].y > 2040, 'New sections start below the existing canvas');
  assert.equal(reopened.store.newtabLayout[key].x, 2340, 'Adding a section leaves existing positions intact');
  const remove = queryAll(reopened.cards().at(-1), 'button').find(node => node.getAttribute('aria-label') === 'Delete Added');
  fire(remove, 'click');
  await settle();
  assert.equal(reopened.store.newtabLayout[addedKey], undefined, 'Deleting a section removes its obsolete position');
  const settings = reopened.settings;
  assert.equal(settings.cleanLayout({ search: { x: Infinity, y: 0 } }).search, undefined);
  assert.equal(settings.cleanLayout({ tabs: { x: 40, y: 20, width: 800 } }).tabs.width, 800);
  assert.equal(settings.cleanLayout({ search: { x: 12, y: 8 } }).search.x, 12, 'Legacy offsets remain readable');
  console.log('PASS newtab canvas: preserved arrangement, collision rollback, cancellation, keyboard movement, scrolling and persistence');
})().catch(error => { console.error(error); process.exitCode = 1; });
